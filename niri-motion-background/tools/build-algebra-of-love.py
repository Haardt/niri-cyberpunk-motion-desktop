def rk4(state,dt,derivative):
    a=derivative(state);b=derivative([v+dt*k/2 for v,k in zip(state,a)])
    c=derivative([v+dt*k/2 for v,k in zip(state,b)]);d=derivative([v+dt*k for v,k in zip(state,c)])
    return [v+dt*(aa+2*bb+2*cc+dd)/6 for v,aa,bb,cc,dd in zip(state,a,b,c,d)]
